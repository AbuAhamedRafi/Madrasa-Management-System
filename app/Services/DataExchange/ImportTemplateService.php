    /**
     * List available versioned templates (F02, UI-02).
     */
    public function listTemplates(array $filters = []): array
    {
        $query = ImportTemplate::where('is_active', true);

        if (!empty($filters['mode'])) {
            $query->where('mode', $filters['mode']);
        }
        if (!empty($filters['version'])) {
            $query->where('version', $filters['version']);
        }

        return $query->get()->map(fn (ImportTemplate $t) => [
            'id' => $t->id,
            'code' => $t->code,
            'name_bn' => $t->name_bn,
            'name_en' => $t->name_en,
            'mode' => $t->mode?->value ?? $t->mode,
            'version' => $t->version,
            'locale' => $t->locale,
            'scheme' => $t->scheme,
            'important_rule_bn' => match ($t->code) {
                'students_create' => 'সার্ভার স্থায়ী স্টুডেন্ট আইডি স্বয়ংক্রিয়ভাবে প্রদান করবে',
                'student_update' => 'লেগ্যাসি আইডি অথবা স্থায়ী আইডি শুধুমাত্র অনুসন্ধানের চাবি',
                'enrollment_stage' => 'বার্ষিক ও সেশন-ভিত্তিক উভয় শিক্ষাকালের জন্য প্রযোজ্য',
                default => 'স্টুডেন্ট আইডি অপরিবর্তনীয়',
            },
            'important_rule_en' => match ($t->code) {
                'students_create' => 'Permanent ID generated by server',
                'student_update' => 'Legacy ID or existing ID for lookup only',
                'enrollment_stage' => 'Year-wise and session-based periods',
                default => 'Student ID is immutable',
            },
        ])->values()->all();
    }

    /**
     * Get template schema details and rules (F02, D08-F02-AT02).
     *
     * @throws DataExchangeDomainException
     */
    public function getSchema(string $code, ?string $version = '1.0'): array
    {
        $template = ImportTemplate::where('code', $code)
            ->where('version', $version)
            ->where('is_active', true)
            ->first();

        if (!$template) {
            throw DataExchangeDomainException::templateUnsupported(
                "Template '{$code}' version '{$version}' is not supported or retired."
            );
        }

        return [
            'code' => $template->code,
            'name_bn' => $template->name_bn,
            'name_en' => $template->name_en,
            'version' => $template->version,
            'mode' => $template->mode?->value ?? $template->mode,
            'schema' => $template->schema_json,
            'forbidden_fields' => match ($template->code) {
                'students_create' => ['student_id', 'admission_status', 'cash_paid', 'receipt_no', 'invoice_amount'],
                'student_update' => ['student_id', 'total_paid', 'paid_status', 'invoice_amount'],
                'enrollment_stage' => ['paid', 'approved', 'payment_cleared', 'billing_cleared', 'fee_totals'],
                default => ['student_id'],
            },
        ];
    }

